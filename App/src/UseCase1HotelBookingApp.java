/**
 * UseCase1HotelBookingApp
 *
 * This class represents the entry point of the Book My Stay
 * Hotel Booking Management System.
 * It demonstrates how a Java application starts execution
 * and prints a welcome message to the console.
 *
 * @author Student
 * @version 1.0
 */
public class UseCase1HotelBookingApp {

    /**
     * Main method - starting point of the Java application.
     * The JVM calls this method when the program is executed.
     *
     * @param args command line arguments
     */
    public static void main(String[] args) {

        // Display welcome message
        System.out.println("====================================");
        System.out.println("      Welcome to Book My Stay       ");
        System.out.println("   Hotel Booking Management System  ");
        System.out.println("           Version 1.0              ");
        System.out.println("====================================");

        // Inform user that application started successfully
        System.out.println("Application started successfully!");
        System.out.println("Thank you for using Book My Stay.");
    }
}
